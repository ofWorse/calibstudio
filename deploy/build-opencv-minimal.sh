#!/usr/bin/env bash
# Builds a minimal, *static* OpenCV for CalibStudio with the MSYS2 UCRT64
# toolchain and writes a qmake include file that CalibStudio.pro picks up.
#
# Why: the MSYS2 OpenCV package is built with FFmpeg, GStreamer and every image
# format, which drags ~190 MB of DLLs into the distribution. CalibStudio needs
# camera capture (DirectShow), image processing, PNG/JPEG
# and calibration, nothing else. Linked statically, only the functions the app
# really calls end up inside CalibStudio.exe, and no OpenCV DLL ships at all.
#
# Nothing is lost: same OpenCV version, same optimised code paths
# (SSE3 baseline + runtime dispatch up to AVX2/AVX-512), Release -O3.
#
# Run from the MSYS2 UCRT64 shell (takes 15-30 minutes):
#   ./deploy/build-opencv-minimal.sh
#
# Result: <project>/third_party/opencv-minimal/  (+ opencv-minimal.pri)
# Then in Qt Creator: Run qmake, Rebuild All, and run deploy-windows.sh again.

set -euo pipefail

OPENCV_VERSION="5.0.0"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"   # folder that holds the sources and build-* dirs
THIRD_PARTY="$PROJECT_DIR/third_party"
SRC_DIR="$THIRD_PARTY/src/opencv-$OPENCV_VERSION"
BUILD_DIR="$THIRD_PARTY/build/opencv-$OPENCV_VERSION-minimal"
INSTALL_DIR="$THIRD_PARTY/opencv-minimal"
PRI_FILE="$INSTALL_DIR/opencv-minimal.pri"

info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

[[ "${MSYSTEM:-}" == "UCRT64" ]] || die "run this script from the 'MSYS2 UCRT64' shell"
for tool in cmake ninja gcc g++ nasm curl bsdtar; do
    command -v "$tool" >/dev/null || die "'$tool' not found. Install: pacman -S --needed mingw-w64-ucrt-x86_64-{cmake,ninja,gcc,nasm,curl,libarchive}"
done

# --- sources ------------------------------------------------------------------
if [[ ! -f "$SRC_DIR/CMakeLists.txt" ]]; then
    info "Downloading OpenCV $OPENCV_VERSION"
    mkdir -p "$THIRD_PARTY/src"
    archive="$THIRD_PARTY/src/opencv-$OPENCV_VERSION.tar.gz"
    curl -fL --retry 3 -o "$archive" \
        "https://github.com/opencv/opencv/archive/refs/tags/$OPENCV_VERSION.tar.gz"
    bsdtar -xf "$archive" -C "$THIRD_PARTY/src"
    rm -f "$archive"
fi

# --- configure ----------------------------------------------------------------
info "Configuring (static, minimal module set)"
rm -rf "$BUILD_DIR" "$INSTALL_DIR"
mkdir -p "$BUILD_DIR"
CONFIGURE_LOG="$BUILD_DIR/configure.log"
cmake -S "$SRC_DIR" -B "$BUILD_DIR" -G Ninja \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX="$INSTALL_DIR" \
    -DBUILD_SHARED_LIBS=OFF \
    -DBUILD_LIST=core,imgproc,imgcodecs,videoio,calib \
    -DBUILD_TESTS=OFF -DBUILD_PERF_TESTS=OFF -DBUILD_EXAMPLES=OFF -DBUILD_DOCS=OFF \
    -DBUILD_opencv_apps=OFF -DBUILD_JAVA=OFF -DBUILD_opencv_python3=OFF \
    \
    -DWITH_DSHOW=ON -DWITH_MSMF=OFF \
    -DWITH_FFMPEG=OFF -DWITH_GSTREAMER=OFF -DWITH_OBSENSOR=OFF -DWITH_1394=OFF \
    \
    -DWITH_PNG=ON -DBUILD_PNG=ON -DWITH_JPEG=ON -DBUILD_JPEG=ON -DBUILD_ZLIB=ON \
    -DWITH_TIFF=OFF -DWITH_WEBP=OFF -DWITH_OPENEXR=OFF -DWITH_JASPER=OFF \
    -DWITH_OPENJPEG=OFF -DWITH_AVIF=OFF -DWITH_JPEGXL=OFF \
    \
    -DWITH_OPENCL=OFF -DWITH_IPP=OFF -DWITH_TBB=OFF -DWITH_OPENMP=OFF \
    -DWITH_EIGEN=OFF -DWITH_LAPACK=OFF -DWITH_PROTOBUF=OFF -DWITH_ADE=OFF \
    -DWITH_ITT=OFF -DWITH_QUIRC=OFF -DWITH_VTK=OFF -DWITH_QT=OFF -DWITH_WIN32UI=OFF \
    -DWITH_KLEIDICV=OFF -DWITH_FLATBUFFERS=OFF \
    -DOPENCV_GENERATE_PKGCONFIG=OFF | tee "$CONFIGURE_LOG"

# Every third-party library must be built from OpenCV's own sources: one found
# in /ucrt64 would turn into a DLL dependency of CalibStudio.exe again.
for lib in ZLib JPEG PNG; do
    grep -Eq "^--[[:space:]]+$lib:[[:space:]]+build" "$CONFIGURE_LOG" \
        || die "$lib is not built from OpenCV's sources (see $CONFIGURE_LOG)"
done
grep -Eq "^--[[:space:]]+DirectShow:[[:space:]]+YES" "$CONFIGURE_LOG" \
    || die "DirectShow backend is disabled (see $CONFIGURE_LOG)"

# --- build + install ----------------------------------------------------------
info "Building (this is the long part)"
cmake --build "$BUILD_DIR" --parallel
cmake --install "$BUILD_DIR" >/dev/null

# --- qmake include file -----------------------------------------------------
info "Writing $(basename "$PRI_FILE")"
header="$(find "$INSTALL_DIR" -path '*/opencv2/core.hpp' -print -quit)"
[[ -n "$header" ]] || die "installed headers not found"
include_dir="$(dirname "$(dirname "$header")")"

mapfile -t archives < <(find "$INSTALL_DIR" -name '*.a' | sort)
(( ${#archives[@]} > 0 )) || die "no static libraries were installed"

{
    echo "# Generated by deploy/build-opencv-minimal.sh - do not edit."
    echo "# Static OpenCV $OPENCV_VERSION: core, imgproc, imgcodecs (PNG/JPEG), videoio (DirectShow), calib."
    echo "OPENCV_MINIMAL = 1"
    echo "INCLUDEPATH += $(cygpath -m "$include_dir")"
    # --start-group/--end-group lets the linker resolve the circular references
    # between OpenCV modules and their bundled 3rd-party libraries in any order.
    echo "LIBS += -Wl,--start-group \\"
    for a in "${archives[@]}"; do
        echo "    $(cygpath -m "$a") \\"
    done
    echo "    -Wl,--end-group"
    # Windows system libraries used by the capture backends (all part of Windows).
    echo "LIBS += -lstrmiids -lole32 -loleaut32 -luuid -lgdi32 -luser32 -lcomdlg32 -lws2_32"
} > "$PRI_FILE"

size="$(du -sh "$INSTALL_DIR" | cut -f1)"
info "Done: ${#archives[@]} static libraries ($size, used only at build time)"
echo "    $(cygpath -w "$PRI_FILE")"
echo "Next: Qt Creator -> Run qmake -> Rebuild All, then ./deploy/deploy-windows.sh --test"
